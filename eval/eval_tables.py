"""All results, organised by research question -> results/eval/tables.md.

usage: eval_tables.py [--root .]
Micro averages; [lo–hi] = bootstrap 95% CI over queries (summary.tsv). Paired differences:
eval/paired.py (2,000 resamples, within clone type for the mean); * = CI excludes 0.
Inputs: results/eval (tree kernels), results/bm25/eval (BM25), results/rq4 (fusion),
results/e5 (false positives), results/rq5 (timing). Missing parts are reported as not run.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paired  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
ROOT = ap.parse_args().root
R = ROOT / "results"
TUNED = {"D": ["STK_l0.8", "SSTK_l0.1", "PTK_l0.4_m0.6"], "C": ["STK_l0.8", "SSTK_l0.1", "PTK_l0.4_m0.6"],
         "B": ["STK_l1.0", "SSTK_l0.1", "PTK_l0.4_m0.6"], "A": ["STK_l1.0", "SSTK_l0.1", "PTK_l0.6_m0.4"]}
DEFAULT = ["STK_l0.4", "SSTK_l0.4", "PTK_l0.4_m0.4"]
MAIN = "D"
TYPES = paired.TYPES
VNAME = {"A": "A raw", "B": "B pruned", "C": "C abstracted", "D": "D + API names"}
KNAME = {"STK": "Subtree (STK)", "SSTK": "Subset tree (SSTK)", "PTK": "Partial tree (PTK)"}
BM = str(R / "bm25/eval/all")
MLT = str(R / "bm25/eval/mlt")
CBZ = str(R / "codebert/eval/zeroshot")
CBF = str(R / "codebert/eval/finetuned")
CBNAME = {CBZ: "CodeBERT zero-shot", CBF: "CodeBERT fine-tuned"}
CBSET = {CBZ: "CLS, cosine", CBF: "CLS, cosine, 5 folds"}


def tk(v, run, root="eval"):
    return str(R / root / v / run)


def load(run):
    f = Path(run) / "eval/summary.tsv"
    if not f.exists():
        return None
    d = {}
    for x in csv.DictReader(open(f), delimiter="\t"):
        d[(x["type"], x["category"], x["averaging"], x["metric"])] = (float(x["value"]), float(x["ci_low"]), float(x["ci_high"]))
    return d


def g(d, t, m, cat="all", avg="micro"):
    return d[(t, cat, avg, m)]


def mean5(d, cat="all", avg="micro"):
    return sum(g(d, t, "AP", cat, avg)[0] for t in TYPES) / 5


def ci(x):
    return f"{x[0]:.3f} [{x[1]:.2f}–{x[2]:.2f}]"


def kernel(run):
    return run.split("_")[0]


def setting(run):
    return ", ".join(("λ " if s[0] == "l" else "μ ") + s[1:] for s in run.split("_")[1:])


def exists(run):
    return (Path(run) / "eval/per_query.tsv").exists()


L = ["# Results by research question", "",
     "584 evaluation queries (100 per clone type, 100 functional) against the reduced corpus of 14,679 BigCloneBench "
     "true positives; KeLP as is; kernel settings tuned on 50 separate tuning queries (`results/grid/`). BM25: Elasticsearch "
     "8.19.15, code-aware tokens, k1 = 1.2, b = 0.75, all query terms (MLT = More Like This with defaults, secondary). "
     "CodeBERT: microsoft/codebert-base, CLS embedding, cosine, 512 tokens; zero-shot, and fine-tuned per functionality "
     "fold (`embed/codebert.py`; each query scored by a model that never saw its functionality). "
     "Micro averages; [lo–hi] = bootstrap 95% CI over queries; paired differences with 95% CI, * = CI excludes 0. "
     "Macro averages and all other metrics are in each run's `eval/summary.tsv`. Generated by `eval/eval_tables.py`.", ""]
bm, mlt = load(BM), load(MLT)

# ================= RQ1
L += ["## RQ1. Syntactic similarity", "", f"MAP per clone type, variant {MAIN} at tuned settings, vs BM25.", "",
      "| Measure | Setting | " + " | ".join(TYPES) + " | Mean |", "|---" * (len(TYPES) + 3) + "|"]
for run in TUNED[MAIN]:
    d = load(tk(MAIN, run))
    L.append(f"| {KNAME[kernel(run)]} | {setting(run)} | " + " | ".join(ci(g(d, t, 'AP')) for t in TYPES) + f" | {mean5(d):.3f} |")
for name, d in (("BM25", bm), ("BM25 (MLT, secondary)", mlt)):
    if d:
        L.append(f"| {name} | k1 1.2, b 0.75 | " + " | ".join(ci(g(d, t, 'AP')) for t in TYPES) + f" | {mean5(d):.3f} |")
for cb in (CBZ, CBF):
    if exists(cb):
        d = load(cb)
        L.append(f"| {CBNAME[cb]} | {CBSET[cb]} | " + " | ".join(ci(g(d, t, 'AP')) for t in TYPES) + f" | {mean5(d):.3f} |")
if bm:
    L += ["", "**Tree kernels vs BM25 (paired)**", ""] + paired.HEAD
    for run in TUNED[MAIN]:
        for m in TYPES + ["mean5"]:
            if kernel(run) == "PTK" or m == "mean5":
                L.append(paired.row(kernel(run), tk(MAIN, run), "BM25", BM, m))
    if exists(CBF):
        L += ["", "**Tree kernels vs fine-tuned CodeBERT, and the baselines against each other (paired)**", ""] + paired.HEAD
        for run in TUNED[MAIN]:
            for m in TYPES + ["mean5"]:
                if kernel(run) == "PTK" or m == "mean5":
                    L.append(paired.row(kernel(run), tk(MAIN, run), "CodeBERT ft", CBF, m))
        L.append(paired.row("CodeBERT ft", CBF, "BM25", BM, "mean5"))
        if exists(CBZ):
            L.append(paired.row("CodeBERT ft", CBF, "CodeBERT zs", CBZ, "mean5"))
    L += ["", "**By task category** (mean MAP over the five types; pattern = 6 algorithmic tasks found by code pattern, "
          "name = 37 tasks found by API names)", "", "| Measure | pattern | name |", "|---|---|---|"]
    for name, d in [(KNAME[kernel(r)], load(tk(MAIN, r))) for r in TUNED[MAIN]] + [("BM25", bm)] \
            + [(CBNAME[c], load(c)) for c in (CBZ, CBF) if exists(c)]:
        try:
            L.append(f"| {name} | {mean5(d, 'pattern'):.3f} | {mean5(d, 'name'):.3f} |")
        except KeyError:
            L.append(f"| {name} | – | – |")

# ================= RQ2
L += ["", "## RQ2. Functional similarity", "",
      f"Functional set (relevant = all methods of the same task), variant {MAIN} at tuned settings, vs BM25.", "",
      "| Measure | MAP@R | MAP | P@10 | R-prec | MAP@R pattern | MAP@R name |", "|---|---|---|---|---|---|---|"]
for name, d in [(KNAME[kernel(r)], load(tk(MAIN, r))) for r in TUNED[MAIN]] + [("BM25", bm), ("BM25 (MLT, secondary)", mlt)] \
        + [(CBNAME[c], load(c)) for c in (CBZ, CBF) if exists(c)]:
    if d:
        L.append(f"| {name} | " + " | ".join(ci(g(d, "functional", m)) for m in ["AP@R", "AP", "P@10", "R-prec"])
                 + f" | {g(d, 'functional', 'AP@R', 'pattern')[0]:.3f} | {g(d, 'functional', 'AP@R', 'name')[0]:.3f} |")
if bm:
    L += ["", "**Tree kernels vs BM25 (paired, MAP@R)**", ""] + paired.HEAD
    for run in TUNED[MAIN]:
        L.append(paired.row(kernel(run), tk(MAIN, run), "BM25", BM, "functional"))
    best_rq2 = max(TUNED, key=lambda v: max(g(load(tk(v, r)), "functional", "AP@R")[0] for r in TUNED[v]))
    r2 = max(TUNED[best_rq2], key=lambda r: g(load(tk(best_rq2, r)), "functional", "AP@R")[0])
    L.append(paired.row(f"best tree kernel overall ({best_rq2} {kernel(r2)})", tk(best_rq2, r2), "BM25", BM, "functional"))
    if exists(CBF):
        L += ["", "**Tree kernels vs fine-tuned CodeBERT, and the baselines against each other (paired, MAP@R)**", ""] + paired.HEAD
        for run in TUNED[MAIN]:
            L.append(paired.row(kernel(run), tk(MAIN, run), "CodeBERT ft", CBF, "functional"))
        L.append(paired.row(f"best tree kernel overall ({best_rq2} {kernel(r2)})", tk(best_rq2, r2), "CodeBERT ft", CBF, "functional"))
        L.append(paired.row("BM25", BM, "CodeBERT ft", CBF, "functional"))
        if exists(CBZ):
            L.append(paired.row("CodeBERT ft", CBF, "CodeBERT zs", CBZ, "functional"))

# ================= RQ3
L += ["", "## RQ3. Representation", "", "### Kernel × variant, tuned settings", "",
      "RQ1 columns: MAP per clone type and the mean over types. RQ2: functional MAP@R.", "",
      "| Variant | Kernel | Setting | " + " | ".join(TYPES) + " | RQ1 mean | RQ2 MAP@R |", "|---" * (len(TYPES) + 5) + "|"]
for v in "ABCD":
    for run in TUNED[v]:
        d = load(tk(v, run))
        L.append(f"| {VNAME[v]} | {kernel(run)} | {setting(run)} | " + " | ".join(f"{g(d, t, 'AP')[0]:.3f}" for t in TYPES)
                 + f" | {mean5(d):.3f} | {g(d, 'functional', 'AP@R')[0]:.3f} |")
L += ["", "### Which kernel? (variant D, paired)", ""] + paired.HEAD
for m in ["mean5", "MT3", "functional"]:
    L.append(paired.row("PTK", tk("D", TUNED["D"][2]), "SSTK", tk("D", TUNED["D"][1]), m))
    L.append(paired.row("PTK", tk("D", TUNED["D"][2]), "STK", tk("D", TUNED["D"][0]), m))
    L.append(paired.row("SSTK", tk("D", TUNED["D"][1]), "STK", tk("D", TUNED["D"][0]), m))
L += ["", "### Which variant? Lexical content inside the trees (paired, tuned settings)", "",
      "A = full tree-sitter tree; B = named nodes with all names and literal text; C = B with every name replaced by "
      "ID/TYPE and every literal by its kind; D = C plus the text of called method names and type names.", ""] + paired.HEAD
for i, k in enumerate(["STK", "SSTK", "PTK"]):
    for m in ["mean5", "functional"]:
        for a, b in (("D", "C"), ("B", "C"), ("B", "D"), ("D", "A"), ("B", "A")):
            L.append(paired.row(f"{a} {k}", tk(a, TUNED[a][i]), f"{b} {k}", tk(b, TUNED[b][i]), m))
L += ["", "### Effect of tuning (secondary): default λ = μ = 0.4 vs tuned (paired)", ""] + paired.HEAD
for v in "DCBA":
    for dr, tr in zip(DEFAULT, TUNED[v]):
        if exists(tk(v, dr)):
            for m in ["mean5", "functional"]:
                L.append(paired.row(f"{v} {kernel(tr)} tuned ({setting(tr)})", tk(v, tr), "default", tk(v, dr), m))

# ================= RQ4
L += ["", "## RQ4. Complementarity", ""]
try:
    import complementarity
    for label, run in (("PTK", tk(MAIN, TUNED[MAIN][2])), ("STK", tk(MAIN, TUNED[MAIN][0]))):
        L += [complementarity.markdown(f"D {label}", run, BM), ""]
    if exists(CBF):
        for label, run in (("PTK", tk(MAIN, TUNED[MAIN][2])), ("STK", tk(MAIN, TUNED[MAIN][0]))):
            L += [complementarity.markdown(f"D {label}", run, CBF, "CodeBERT ft"), ""]
        L += [complementarity.markdown("CodeBERT ft", CBF, BM), ""]
    L += ["Queries: which measure has the higher AP (MAP@R for functional). Items: a relevant item is found if ranked "
          "within the top R (R = number of relevant items). Top-10 overlap: share of the top 10 returned by both.", ""]
except Exception as e:  # noqa: BLE001
    L += [f"(complementarity not available: {e})", ""]
for name, tkrun, obj, oname, orun in (
        ("rq1_PTK", tk(MAIN, TUNED[MAIN][2]), "RQ1 mean MAP", "BM25", BM),
        ("rq2_STK", tk(MAIN, TUNED[MAIN][0]), "RQ2 MAP@R", "BM25", BM),
        ("rq1_PTK_codebert", tk(MAIN, TUNED[MAIN][2]), "RQ1 mean MAP", "CodeBERT ft", CBF),
        ("rq2_STK_codebert", tk(MAIN, TUNED[MAIN][0]), "RQ2 MAP@R", "CodeBERT ft", CBF)):
    d = R / "rq4" / name
    if not (d / "tuning.tsv").exists():
        continue
    rows = list(csv.DictReader(open(d / "tuning.tsv"), delimiter="\t"))
    col = [c for c in rows[0] if c != "w"][0]
    best = max(rows, key=lambda r: (round(float(r[col]), 6), float(r["w"])))["w"]
    L += [f"**Fusion, {'RQ1: D PTK' if name.startswith('rq1') else 'RQ2: D STK'} + {oname}**", "",
          f"Weighted sum W·TK + (1 − W)·{oname}/max ({'exp(cosine)' if oname != 'BM25' else 'BM25 score'} divided by the query's maximum), W tuned on the tuning queries ({obj}): "
          + ", ".join(f"W {r['w']}: {float(r[col]):.3f}" for r in rows) + f". Selected W = {best}. "
          "RRF: reciprocal rank fusion, k = 60 (no parameter).", ""] + paired.HEAD
    ms = ["ST3", "MT3", "mean5"] if name.startswith("rq1") else ["functional"]
    for fused, lab in ((str(d / f"wsum_w{best}"), f"wsum W={best}"), (str(d / "rrf"), "RRF")):
        for mm in ms:
            L.append(paired.row(lab, fused, kernel(Path(tkrun).name), tkrun, mm))
            L.append(paired.row(lab, fused, oname, orun, mm))
    L.append("")

# ================= E5
L += ["## E5. Robustness: false positives added to the corpus", ""]
e5runs = [(KNAME[kernel(r)], tk(MAIN, r, "e5")) for r in TUNED[MAIN]] + [("BM25", str(R / "bm25/e5/all"))]
if all(exists(x) for _, x in e5runs):
    n5 = len((Path(e5runs[0][1]) / "corpus_ids.txt").read_text().split())
    L += [f"Corpus = the 14,679 true positives plus {n5 - 14679:,} false positives ({n5:,} methods); same queries and "
          "ground truth (false positives are never relevant). In brackets: change vs the main corpus.", "",
          "| Measure | " + " | ".join(TYPES) + " | Mean | Functional MAP@R |", "|---" * (len(TYPES) + 3) + "|"]
    mains = [tk(MAIN, r) for r in TUNED[MAIN]] + [BM]
    for (name, run), mrun in zip(e5runs, mains):
        d, dm = load(run), load(mrun)
        L.append(f"| {name} | " + " | ".join(f"{g(d, t, 'AP')[0]:.3f} ({g(d, t, 'AP')[0] - g(dm, t, 'AP')[0]:+.3f})" for t in TYPES)
                 + f" | {mean5(d):.3f} ({mean5(d) - mean5(dm):+.3f}) | {g(d, 'functional', 'AP@R')[0]:.3f} "
                 f"({g(d, 'functional', 'AP@R')[0] - g(dm, 'functional', 'AP@R')[0]:+.3f}) |")
    for cb, c5 in ((CBZ, str(R / "codebert/e5/zeroshot")), (CBF, str(R / "codebert/e5/finetuned"))):
        if exists(c5):
            d, dm = load(c5), load(cb)
            L.append(f"| {CBNAME[cb]} | " + " | ".join(f"{g(d, t, 'AP')[0]:.3f} ({g(d, t, 'AP')[0] - g(dm, t, 'AP')[0]:+.3f})" for t in TYPES)
                     + f" | {mean5(d):.3f} ({mean5(d) - mean5(dm):+.3f}) | {g(d, 'functional', 'AP@R')[0]:.3f} "
                     f"({g(d, 'functional', 'AP@R')[0] - g(dm, 'functional', 'AP@R')[0]:+.3f}) |")
    L += ["", "**Paired on the E5 corpus**", ""] + paired.HEAD
    for m in ["mean5", "MT3", "functional"]:
        L.append(paired.row("PTK", e5runs[2][1], "BM25", e5runs[3][1], m))
        L.append(paired.row("STK", e5runs[0][1], "BM25", e5runs[3][1], m))
        if exists(str(R / "codebert/e5/finetuned")):
            L.append(paired.row("PTK", e5runs[2][1], "CodeBERT ft", str(R / "codebert/e5/finetuned"), m))
            L.append(paired.row("STK", e5runs[0][1], "CodeBERT ft", str(R / "codebert/e5/finetuned"), m))
    L.append("")
else:
    L += ["Not run yet.", ""]

# ================= RQ5
L += ["## RQ5. Cost", ""]
tf = R / "rq5/tree_kernels.tsv"
if tf.exists():
    by = {}
    for r in csv.DictReader(open(tf), delimiter="\t"):
        by.setdefault((r["variant"], r["kernel"], r["setting"]), {})[int(r["queries"])] = (float(r["wall_s"]), int(r["max_rss_kb"]))
    L += ["One thread, idle machine, 20 timing queries against the 14,679-method corpus. "
          "One-off = JVM start, parsing the corpus trees and computing their self-similarities (run with 0 queries); "
          "per query = (time with 20 queries − one-off) / 20, i.e. one query scored against the whole corpus.", "",
          "| Variant | Kernel | Setting | One-off (s) | Per query (s) | Per pair (ms) | Peak RSS (MB) |", "|---|---|---|---|---|---|---|"]
    for (v, k, s), x in by.items():
        if 0 in x and 20 in x:
            pq = (x[20][0] - x[0][0]) / 20
            lam, mu = (z.split("=")[1] for z in s.split(","))
            st = f"λ {lam}" + (f", μ {mu}" if k == "PTK" else "")
            L.append(f"| {VNAME[v]} | {k} | {st} | {x[0][0]:.1f} | {pq:.2f} | {pq / 14678 * 1000:.3f} | {max(x[0][1], x[20][1]) / 1024:.0f} |")
    bi = R / "rq5/bm25_index.json"
    bt = R / "rq5/runs/bm25_timing_queries/timing.tsv"
    if bi.exists() and bt.exists():
        b = json.loads(bi.read_text())
        t = list(csv.DictReader(open(bt), delimiter="\t"))
        took = sorted(float(r["es_took_ms"]) for r in t)
        cl = sorted(float(r["client_ms"]) for r in t)
        jvm = json.loads((R / "rq5/bm25_jvm.json").read_text()) if (R / "rq5/bm25_jvm.json").exists() else {}
        L += ["", "| BM25 | Index build (s) | Index size (MB) | Per query, Elasticsearch `took` (ms, mean; min–max) | "
              "Per query incl. returning all 14,679 scores (ms, mean) | JVM heap in use after the queries (MB; -Xmx 2 GB) |", "|---|---|---|---|---|---|",
              f"| Elasticsearch | {b['index_seconds']:.1f} | {b['store_bytes'] / 1e6:.1f} | {sum(took) / len(took):.0f}; "
              f"{took[0]:.0f}–{took[-1]:.0f} | {sum(cl) / len(cl):.0f} | {jvm.get('heap_used_in_bytes', 0) / 2**20:.0f} |"]
    cj = R / "rq5/codebert.json"
    if cj.exists():
        c = json.loads(cj.read_text())
        tm = [json.loads(f.read_text()) for f in sorted((ROOT / "data/codebert/models").glob("fold*/train_meta.json"))]
        enc = ROOT / "data/codebert/emb/zeroshot_main.npy.json"
        L += ["", "| CodeBERT (1 thread) | Model load (s) | Encoding per method (ms) | Corpus encoding, estimated (s) | "
              "Per query: encode + cosine vs corpus (s, mean; min–max) |", "|---|---|---|---|---|",
              f"| codebert-base, bf16 autocast | {c['model_load_s']:.1f} | {c['encode_ms_per_method_mean']:.0f} | "
              f"{c['corpus_encoding_s_estimate']:.0f} | {c['query_s_mean']:.2f}; {c['query_s_min']:.2f}–{c['query_s_max']:.2f} |"]
        if enc.exists():
            L.append(f"\nCorpus encoding actually used (8 threads, batches of 32): "
                     f"{json.loads(enc.read_text())['seconds']:.0f} s.")
        if tm:
            L.append(f"Fine-tuning (8 threads, {tm[0]['steps']} steps of {tm[0]['pairs_per_batch']} pairs): "
                     + ", ".join(f"fold {x['fold']} {x['seconds'] / 60:.0f} min" for x in tm)
                     + f"; total {sum(x['seconds'] for x in tm) / 3600:.1f} h.")
    tb = R / "rq5/tree_building.tsv"
    if tb.exists():
        L += ["", "**Preparation per method** (Python; tree-sitter parse, tree variants, BM25 tokens)", "",
              "| Step | Total for 14,679 methods (s) | Per method (ms) |", "|---|---|---|"]
        for r in csv.DictReader(open(tb), delimiter="\t"):
            L.append(f"| {r['step']} | {float(r['seconds']):.1f} | {float(r['ms_per_method']):.2f} |")
    L.append("")
else:
    L += ["Not run yet.", ""]

(R / "eval/tables.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
